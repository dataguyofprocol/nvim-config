// Regenerate with: node scripts/build-python-errors.mjs [package.nls.en-us.json]
import { readFile, writeFile } from 'node:fs/promises';

const version = '1.1.408';
const url = `https://raw.githubusercontent.com/microsoft/pyright/${version}/packages/pyright-internal/src/localization/package.nls.en-us.json`;
const translations = JSON.parse(await readFile(new URL('./python-errors-translations.json', import.meta.url), 'utf8'));
let source;
if (process.argv[2]) {
    source = JSON.parse(await readFile(process.argv[2], 'utf8'));
} else {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Pyright templates: HTTP ${response.status}`);
    source = await response.json();
}

const quote = value => {
    if (value.includes(']=]')) throw new Error('Unsupported Lua long-string delimiter');
    return `[=[${value}]=]`;
};
const placeholders = text => [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]);
const rules = Object.entries(translations).map(([id, explanation]) => {
    const entry = source.Diagnostic[id];
    const template = typeof entry === 'string' ? entry : entry?.message;
    if (!template) throw new Error(`Unknown Pyright localization key: ${id}`);
    if (template.includes('\n')) throw new Error(`Multiline headline: ${id}`);
    const names = new Set(placeholders(template));
    for (const name of placeholders(explanation)) {
        if (!names.has(name)) throw new Error(`${id}: unknown placeholder ${name}`);
    }
    for (const name of names) {
        if (!placeholders(explanation).includes(name)) throw new Error(`${id}: explanation loses ${name}`);
    }
    return { id, template, explanation };
});
// Literal specificity keeps None messages ahead of generic type placeholders.
const specificity = rule => rule.template.replace(/\{\w+\}/g, '').length;
rules.sort((a, b) => specificity(b) - specificity(a) || a.id.localeCompare(b.id));
const lines = [
    `-- Generated by scripts/build-python-errors.mjs from Pyright ${version} (MIT).`,
    `-- Source: ${url}`,
    '-- Edit scripts/python-errors-translations.json, then regenerate this file.',
    'return {',
];
for (const { id, template, explanation } of rules) {
    lines.push(`    { -- ${id}`, `        ${quote(template)},`, `        ${quote(explanation)},`, '    },');
}
lines.push('}', '');
await writeFile(new URL('../lua/batra/python_errors/rules.lua', import.meta.url), lines.join('\n'));
console.log(`Generated ${rules.length} Python diagnostic translations from Pyright ${version}`);
